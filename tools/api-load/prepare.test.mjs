import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, mkdir, rm, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { snapshot, prepare, verifyInputs, validateSpec, validateSelection, validateResearch, sha256 } from './prepare.mjs';

const example = fileURLToPath(new URL('../../docs/examples/api-load/', import.meta.url));
const target = 'http://127.0.0.1:8080';
const json = async file => JSON.parse(await readFile(file, 'utf8'));
const writeJson = (file, value) => writeFile(file, JSON.stringify(value));

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'testforge-api-load-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const before = process.env.TESTFORGE_API_LOAD_TARGET;
  process.env.TESTFORGE_API_LOAD_TARGET = target;
  t.after(() => before === undefined ? delete process.env.TESTFORGE_API_LOAD_TARGET
    : process.env.TESTFORGE_API_LOAD_TARGET = before);
  const run = join(root, 'run');
  const options = { spec: join(example, 'openapi.json'), selection: join(example, 'operations.json'),
    scenario: join(example, 'scenario'), run };
  await snapshot(options);
  const selected = await json(join(run, 'input/operations.json'));
  const discovery = { enabled: true, healthy: true, specs: [{ specId: 'api', failed: false }] };
  const catalog = { specId: 'api', endpoints: selected.map(key => ({ key })) };
  const exploration = { enabled: true, healthy: true, specs: [{ specId: 'api', baseUrl: target,
    observations: selected.map(key => ({ key, outcome: 'PASSED' })) }] };
  await mkdir(join(run, 'discovery/api'), { recursive: true });
  await mkdir(join(run, 'exploration'));
  await writeJson(join(run, 'discovery/report.json'), discovery);
  await writeJson(join(run, 'discovery/api/catalog.json'), catalog);
  await writeJson(join(run, 'exploration/report.json'), exploration);
  const inputs = await json(join(run, 'inputs.json'));
  const files = {};
  for (const path of ['discovery/report.json', 'discovery/api/catalog.json', 'exploration/report.json'])
    files[path] = sha256(await readFile(join(run, path)));
  await writeJson(join(run, 'research.json'), { formatVersion: 1, files,
    specSha256: inputs.files['openapi.json'], targetSha256: sha256(target) });
  return { root, run, options, selected, discovery, catalog, exploration };
}

test('upstream generator produces a portable native client and preserves the project scenario', async t => {
  const f = await fixture(t);
  const prepared = await prepare({ run: f.run });
  const client = await readFile(join(prepared, 'client.ts'), 'utf8');
  assert.match(client, /Automatically generated by @grafana\/openapi-to-k6: 0\.4\.1/);
  assert.match(client, /\.\/vendor\/url\.js/);
  assert.doesNotMatch(client, /https:\/\/jslib\.k6\.io/);
  assert.equal(await readFile(join(prepared, 'scenario.ts'), 'utf8'),
    await readFile(join(example, 'scenario/scenario.ts'), 'utf8'));
  const provenance = await json(join(prepared, 'provenance.json'));
  assert.deepEqual(provenance.selectedOperations, f.selected);
  assert.equal(provenance.generatorVersion, '0.4.1');
  for (const [path, hash] of Object.entries(provenance.files))
    assert.equal(sha256(await readFile(join(prepared, path))), hash);
});

test('selection requires explicit operations and explicit opt-in for writes', () => {
  assert.throws(() => validateSelection([]), /non-empty/);
  assert.throws(() => validateSelection(['GET /health', 'GET /health']), /repeat/);
  assert.throws(() => validateSelection(['POST /api/v1/tasks']), /explicit/);
  assert.deepEqual(validateSelection(['POST /api/v1/tasks'], true), ['POST /api/v1/tasks']);
});

test('bundled specs cannot fetch external references during research or generation', () => {
  assert.throws(() => validateSpec({ openapi: '3.0.3', components: { schemas: { X: { $ref: 'https://other/schema' } } } }),
    /Bundle external/);
});

test('skipped, mismatching, missing and differently targeted operations cannot feed load', async t => {
  const f = await fixture(t);
  for (const outcome of ['SKIPPED', 'CONTRACT_MISMATCH', 'FAILED']) {
    const report = structuredClone(f.exploration);
    report.specs[0].observations[0].outcome = outcome;
    assert.throws(() => validateResearch(f.discovery, f.catalog, report, f.selected, sha256(target)), /successfully explored/);
  }
  assert.throws(() => validateResearch(f.discovery, f.catalog, f.exploration, ['GET /missing'], sha256(target)), /absent/);
  assert.throws(() => validateResearch(f.discovery, f.catalog, f.exploration, f.selected, sha256('http://other')), /target differ/);
  assert.throws(() => validateResearch({ enabled: false }, f.catalog, f.exploration, f.selected, sha256(target)), /Discovery/);
});

test('changed inputs, changed reports and retargeting fail before generation', async t => {
  const f = await fixture(t);
  process.env.TESTFORGE_API_LOAD_TARGET = 'http://other';
  await assert.rejects(prepare({ run: f.run }), /target differ/);
  process.env.TESTFORGE_API_LOAD_TARGET = target;
  await writeFile(join(f.run, 'exploration/report.json'), '{}');
  await assert.rejects(prepare({ run: f.run }), /artifact changed/);
  await assert.rejects(access(join(f.run, 'prepared')));
  await writeFile(join(f.run, 'input/scenario/scenario.ts'), '// changed after research');
  await assert.rejects(verifyInputs(f.run), /snapshot changed/);
});

test('an existing run cannot contribute stale outputs and output cannot overlap inputs', async t => {
  const f = await fixture(t);
  await assert.rejects(snapshot(f.options), /EEXIST/);
  await assert.rejects(snapshot({ ...f.options, run: join(f.options.scenario, 'output') }), /outside/);
});
